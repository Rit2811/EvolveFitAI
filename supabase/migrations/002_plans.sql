create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  workout_plan jsonb not null,
  meal_plan jsonb not null,
  summary text not null,
  adaptation_message text not null,
  adaptation_reasons jsonb not null default '[]'::jsonb,
  version integer not null default 1 check (version > 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index plans_one_active_per_user on public.plans (user_id) where is_active = true;
alter table public.plans enable row level security;
create policy "Users can view their plans" on public.plans for select using (auth.uid() = user_id);
create policy "Users can create their plans" on public.plans for insert with check (auth.uid() = user_id);
create policy "Users can update their plans" on public.plans for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete their plans" on public.plans for delete using (auth.uid() = user_id);
