create table if not exists public.check_ins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  energy integer not null check (energy between 1 and 5),
  sleep_hours numeric not null check (sleep_hours between 0 and 24),
  sleep_quality integer not null check (sleep_quality between 1 and 5),
  soreness integer not null check (soreness between 1 and 5),
  stress integer not null check (stress between 1 and 5),
  hunger integer not null check (hunger between 1 and 5),
  workout_completed boolean not null default false,
  diet_adherence integer not null check (diet_adherence between 1 and 5),
  readiness_score integer not null check (readiness_score between 0 and 100),
  notes text not null default '',
  created_at timestamptz not null default now()
);

alter table public.check_ins enable row level security;
create policy "Users can view their check-ins" on public.check_ins for select using (auth.uid() = user_id);
create policy "Users can create their check-ins" on public.check_ins for insert with check (auth.uid() = user_id);
create policy "Users can update their check-ins" on public.check_ins for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete their check-ins" on public.check_ins for delete using (auth.uid() = user_id);
